import { API_V1_URL, SOCKET_URL } from "../config/constants";

/**
 * FE-03 — the one safe-URL helper for server-controlled media values.
 *
 * Policy (deliberate, do not loosen casually):
 * - A value is cleaned BEFORE it is parsed: ASCII control characters
 *   (U+0000–U+001F, U+007F) are stripped everywhere and the value is
 *   trimmed, because browsers ignore \t \n \r inside a scheme
 *   ("java\tscript:") — a parser that does not strip them first can be
 *   fooled into seeing a different scheme than the browser executes.
 * - Absolute URLs are accepted only when ALL of these hold:
 *     · the scheme is https:, OR http: when the URL's origin is exactly
 *       one of the app's own configured origins AND that configured
 *       origin itself uses http: (the dev/test case: the app is
 *       configured with VITE_API_BASE_URL=http://localhost:3001, so an
 *       https-only rule would break every local upload). Upgrading an
 *       own host from its configured http: to https: is also accepted;
 *       downgrading an allowlisted https host to http: never is.
 *     · there is no userinfo, no backslash, and no quote / angle /
 *       backtick character anywhere in the raw value (quotes are what
 *       let a value break out of the CSS url('…') token in
 *       ImageMagnifier — such values are rejected, never escaped).
 *     · the hostname is exactly on the allowlist below. Hostname
 *       equality is checked on the URL-parser-normalised (punycode)
 *       hostname, so subdomain tricks (res.cloudinary.com.evil.com,
 *       evilres.cloudinary.com), userinfo tricks
 *       (res.cloudinary.com@evil.com) and IDN/Cyrillic lookalikes
 *       (which normalise to xn--… names that are not on the list) all
 *       fail.
 * - Allowlist: the hosts of the app's own configured origins
 *   (API_V1_URL and SOCKET_URL from src/config/constants.js, i.e. the
 *   API/uploads origin), res.cloudinary.com (product/blog/chat media),
 *   images.unsplash.com (fallback + editorial media),
 *   fabritor.s3.ap-southeast-1
 *   .amazonaws.com (the evidenced AR model host, ARViewPage), and the
 *   generic S3 bucket pattern <bucket>.s3.<region>.amazonaws.com —
 *   justified because AR model files are admin-uploaded to S3 buckets
 *   in the same shape as the evidenced host; the pattern still pins
 *   the amazonaws.com suffix and the s3 label, it is not a wildcard.
 * - Protocol-relative values ("//host/path") are treated as https
 *   candidates and must pass the same allowlist; a leading "/\" or
 *   "\\" is rejected outright (browsers treat backslashes as slashes
 *   in special-scheme URLs, which would smuggle a protocol-relative
 *   value past a "/" check).
 * - Site-relative paths (exactly one leading "/", no backslash, no
 *   scheme) and bare relative paths with no scheme colon are returned
 *   unchanged so callers keep the existing base-joining behaviour.
 *   Anything with a percent-encoded first segment is rejected: a
 *   legitimate media path never needs "%2f"/"%6a…" up front, and
 *   double-encoded values must not be reinterpreted downstream.
 * - Everything else returns the caller's fallback — NEVER the raw
 *   value.
 */

// Hostnames that are always allowed, https only.
const FIXED_HTTPS_HOSTS = new Set([
  "res.cloudinary.com",
  "images.unsplash.com",
  // FE-06: the external avatar-placeholder host that used to be
  // listed here (its URLs were generated by getAvatarUrl itself,
  // carrying user names) was removed — nothing may generate or
  // accept those URLs any more; avatars render locally as initials.
  // Evidenced AR model host (src/pages/shop/ARViewPage.jsx).
  "fabritor.s3.ap-southeast-1.amazonaws.com",
]);

// <bucket>.s3.<region>.amazonaws.com — see the policy comment above.
const S3_BUCKET_HOST = /^[^.]+\.s3\.[a-z0-9-]+\.amazonaws\.com$/;

// The app's own configured origins (API + uploads/socket). Parsed once;
// a malformed configured value yields no own-origin entries (the config
// layer already throws on a bad API URL at boot/build time).
const OWN_ORIGINS = [API_V1_URL, SOCKET_URL]
  .map((value) => {
    try {
      return new URL(value);
    } catch {
      return null;
    }
  })
  .filter(Boolean);

// eslint-disable-next-line no-control-regex -- stripping control chars is the point (see policy comment)
const CONTROL_CHARS = /[\u0000-\u001f\u007f]/g;
// Characters that must never survive into any sink: quotes/backtick
// break the CSS url('…') token and HTML attributes, "<"/">" break
// markup, "\" is a slash in disguise for special-scheme URLs.
const FORBIDDEN_CHARS = /["'`< >\\]/;
const SCHEME_RE = /^([a-zA-Z][a-zA-Z0-9+.-]*):/;

/** Strip control characters everywhere and trim (see policy above). */
export function cleanUrlValue(raw) {
  if (typeof raw !== "string") return null;
  const cleaned = raw.replace(CONTROL_CHARS, "").trim();
  return cleaned || null;
}

function isOwnOrigin(url) {
  return OWN_ORIGINS.some(
    (own) =>
      url.host === own.host &&
      (url.protocol === own.protocol || url.protocol === "https:")
  );
}

function isAllowlistedAbsolute(url, fixedHosts, allowS3Pattern) {
  if (url.username || url.password) return false;
  if (isOwnOrigin(url)) return true;
  if (url.protocol !== "https:") return false;
  if (fixedHosts.has(url.hostname)) return true;
  if (allowS3Pattern && S3_BUCKET_HOST.test(url.hostname)) return true;
  return false;
}

/**
 * True when the (cleaned) value claims to be an absolute URL — a
 * scheme, a protocol-relative "//", or a backslash-led form. Callers
 * (imageUrl.js) use this to decide between validateMediaUrl and the
 * relative-path base-joining branch.
 */
export function isAbsoluteUrlCandidate(raw) {
  const cleaned = cleanUrlValue(raw);
  if (!cleaned) return false;
  return (
    SCHEME_RE.test(cleaned) ||
    cleaned.startsWith("//") ||
    cleaned.startsWith("/\\") ||
    cleaned.startsWith("\\")
  );
}

/**
 * Validate a server-controlled media URL.
 *
 * @param {*} raw - Untrusted value (product/chat/announcement field…).
 * @param {object} [options]
 * @param {*} [options.fallback=null] - Returned for every rejected
 *   value. Pass the sink's existing fallback (e.g. FALLBACK_IMAGES)
 *   or null when the sink should render nothing.
 * @param {boolean} [options.allowBlob=false] - Accept a blob: URL.
 *   ONLY for the local optimistic chat preview: a blob: URL can only
 *   be minted by this page (URL.createObjectURL), so a server payload
 *   must never be allowed to supply one.
 * @param {Set<string>|string[]} [options.allowedHosts] - REPLACES the
 *   fixed external host set for this call (own configured origins are
 *   always allowed). Chat attachments use this: API origin or
 *   Cloudinary only.
 * @returns {string|*} The validated URL (parser-normalised for
 *   absolute URLs, unchanged for safe relative paths) or `fallback`.
 */
export function validateMediaUrl(raw, options = {}) {
  const { fallback = null, allowBlob = false } = options;
  // When a caller restricts the host set (chat attachments), that set
  // REPLACES the fixed set and the S3 pattern no longer applies. Own
  // configured origins are always allowed.
  const fixedHosts = options.allowedHosts
    ? new Set(options.allowedHosts)
    : FIXED_HTTPS_HOSTS;
  const allowS3Pattern = !options.allowedHosts;

  const cleaned = cleanUrlValue(raw);
  if (!cleaned) return fallback;
  if (FORBIDDEN_CHARS.test(cleaned)) return fallback;

  // blob: — local optimistic previews only, and only in the exact
  // shape the browser mints: blob:<http(s) origin>/<id>.
  if (/^blob:/i.test(cleaned)) {
    if (!allowBlob) return fallback;
    try {
      const inner = new URL(cleaned.slice("blob:".length));
      if (inner.protocol !== "http:" && inner.protocol !== "https:") {
        return fallback;
      }
      return cleaned;
    } catch {
      return fallback;
    }
  }

  // Protocol-relative: an https candidate that must pass the allowlist.
  if (cleaned.startsWith("//")) {
    try {
      const url = new URL(`https:${cleaned}`);
      return isAllowlistedAbsolute(url, fixedHosts, allowS3Pattern) ? url.href : fallback;
    } catch {
      return fallback;
    }
  }
  if (cleaned.startsWith("/\\") || cleaned.startsWith("\\")) return fallback;

  const schemeMatch = cleaned.match(SCHEME_RE);
  if (schemeMatch) {
    const scheme = schemeMatch[1].toLowerCase();
    if (scheme !== "http" && scheme !== "https") return fallback;
    // Require the authority form; "https:evil.com" is resolved by
    // browsers against the page origin in surprising ways — reject.
    if (!cleaned.slice(schemeMatch[0].length).startsWith("//")) {
      return fallback;
    }
    try {
      const url = new URL(cleaned);
      return isAllowlistedAbsolute(url, fixedHosts, allowS3Pattern) ? url.href : fallback;
    } catch {
      return fallback;
    }
  }

  // A percent-encoded first segment is never legitimate media input
  // ("%6aavascript:…", "%252f%252fevil.com", "java%73cript:…"): do not
  // let a downstream decoder reinterpret it as a scheme or a "//".
  const firstSegment = cleaned.split("/")[0];
  if (firstSegment.includes("%")) return fallback;
  // A colon anywhere before the first slash that was not a scheme we
  // accepted above (e.g. "java%73cript:" handled by the % rule, or a
  // scheme with illegal characters) is not a relative path.
  if (firstSegment.includes(":")) return fallback;

  // Site-relative (single leading "/") or bare relative path: safe to
  // hand back for the caller's existing base-joining behaviour.
  return cleaned;
}

/**
 * FE-04 — validate a stored actionUrl (notification / announcement)
 * for use as a navigation target.
 *
 * @param {*} raw - Stored actionUrl value.
 * @param {object} [options]
 * @param {string|number} [options.highlight] - Optional id merged into
 *   in-app targets as the `highlight` query param via URLSearchParams (existing
 *   query params are preserved; the id is encoded, so an id
 *   containing &, #, ? or "=pwn" cannot inject extra params or a
 *   fragment; an existing highlight param is replaced, not duplicated).
 * @param {boolean} [options.inAppOnly=false] - When true, only in-app
 *   targets are returned (external URLs → null). Router consumers
 *   (NotificationBell, AdminLayout toasts) pass this: navigate()
 *   must never be handed an off-site URL.
 * @returns {string|null} A safe target, or null:
 *   - Site-relative paths (exactly one leading "/"; "//", "/\" and
 *     anything with a scheme, backslash or whitespace are rejected)
 *     are returned as path+query+hash, with a LEADING "/admin" path
 *     segment rewritten to "/dashboard" (only the first segment —
 *     "/orders/admin" and "/administrator" are untouched).
 *   - Absolute URLs are accepted only over https: (http: only for
 *     the app's own origin / configured origins) on the media
 *     allowlist or the app's own origin. Own-origin URLs are reduced
 *     to their path+query+hash (and get the same /admin rewrite);
 *     other allowlisted absolute URLs are returned whole unless
 *     inAppOnly is set.
 *   - Everything else → null. Callers must not navigate on null
 *     (mark-as-read etc. still happens).
 */
export function safeActionUrl(raw, options = {}) {
  const { highlight = null, inAppOnly = false } = options;
  const cleaned = cleanUrlValue(raw);
  if (!cleaned) return null;
  if (/["'`< >\\]/.test(cleaned) || /\s/.test(cleaned)) return null;

  const finishInApp = (pathAndQueryAndHash) => {
    // Split off the fragment first so query handling cannot touch it.
    const hashIdx = pathAndQueryAndHash.indexOf("#");
    const hash = hashIdx >= 0 ? pathAndQueryAndHash.slice(hashIdx) : "";
    const beforeHash = hashIdx >= 0 ? pathAndQueryAndHash.slice(0, hashIdx) : pathAndQueryAndHash;
    const qIdx = beforeHash.indexOf("?");
    let pathname = qIdx >= 0 ? beforeHash.slice(0, qIdx) : beforeHash;
    const params = new URLSearchParams(qIdx >= 0 ? beforeHash.slice(qIdx + 1) : "");
    // Rewrite a LEADING "/admin" segment only.
    if (pathname === "/admin") pathname = "/dashboard";
    else if (pathname.startsWith("/admin/")) pathname = `/dashboard${pathname.slice("/admin".length)}`;
    if (highlight !== null && highlight !== undefined && highlight !== "") {
      params.set("highlight", String(highlight));
    }
    const qs = params.toString();
    return `${pathname}${qs ? `?${qs}` : ""}${hash}`;
  };

  // Site-relative: exactly one leading slash.
  if (cleaned.startsWith("/")) {
    if (cleaned.startsWith("//") || cleaned.startsWith("/\\")) return null;
    return finishInApp(cleaned);
  }

  // Absolute: scheme required, https (or own-origin http), allowlist.
  if (!SCHEME_RE.test(cleaned)) return null;
  let url;
  try {
    url = new URL(cleaned);
  } catch {
    return null;
  }
  if (url.username || url.password) return null;
  const appHost = typeof window !== "undefined" ? window.location?.host : null;
  const isAppOrigin = appHost !== null && url.host === appHost;
  const isConfiguredOrigin = OWN_ORIGINS.some((own) => url.host === own.host);
  if (isAppOrigin || isConfiguredOrigin) {
    if (url.protocol !== "https:" && url.protocol !== "http:") return null;
    return finishInApp(`${url.pathname}${url.search}${url.hash}`);
  }
  if (url.protocol !== "https:") return null;
  if (!FIXED_HTTPS_HOSTS.has(url.hostname) && !S3_BUCKET_HOST.test(url.hostname)) {
    return null;
  }
  return inAppOnly ? null : url.href;
}

/**
 * FE-04 (sibling) — validate an EXTERNAL attribution URL (blog
 * `originalUrl` / `source.logo` on BlogDetailsPage).
 *
 * Linking out to arbitrary publisher sites IS the feature here, so —
 * unlike validateMediaUrl — there is deliberately NO host allowlist:
 * any host may be linked. What must never survive is a non-https
 * scheme: a `javascript:` href executes on click, and a `data:` /
 * `javascript:` value in the logo `src` is the same stored-value
 * abuse. The value is cleaned exactly like the module's other
 * helpers (control characters stripped everywhere, then trimmed —
 * browsers ignore \t \n \r inside a scheme, so "java\tscript:" must
 * be judged as the "javascript:" it becomes) and parsed with URL();
 * only an https: result is accepted.
 *
 * @param {*} raw - Untrusted server-controlled value.
 * @returns {string|null} The parser-normalised href, or null when
 *   the value is not a clean https: URL. Callers render nothing on
 *   null — never the raw value.
 */
export function validateExternalUrl(raw) {
  const cleaned = cleanUrlValue(raw);
  if (!cleaned) return null;
  let url;
  try {
    url = new URL(cleaned);
  } catch {
    return null;
  }
  if (url.protocol !== "https:") return null;
  return url.href;
}

export default validateMediaUrl;
